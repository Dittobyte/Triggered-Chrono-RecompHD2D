"""Generate the Triggered Chrono logo lockups (SVG, then PNG).

Original artwork: capitals drawn on a 5x7 grid below, plus the time-ring from
packaging/icons/make_icons.py. No fonts, nothing traced, no game imagery.

  packaging/branding/make_logo.py      writes triggered-chrono-{stacked,horizontal,wordmark}.svg/.png here

PNGs use rsvg-convert, else ImageMagick. The outputs are committed.
"""
import os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
G = {"T": "11111,00100,00100,00100,00100,00100,00100", "R": "11110,10001,10001,11110,10100,10010,10001",
     "I": "11111,00100,00100,00100,00100,00100,11111", "G": "01111,10000,10000,10011,10001,10001,01111",
     "E": "11111,10000,10000,11110,10000,10000,11111", "D": "11110,10001,10001,10001,10001,10001,11110",
     "C": "01111,10000,10000,10000,10000,10000,01111", "H": "10001,10001,10001,11111,10001,10001,10001",
     "O": "01110,10001,10001,10001,10001,10001,01110", "N": "10001,11001,10101,10101,10011,10001,10001"}
CELL, GAP, LW, LH, DARK = 10, 10, 50, 70, "#1d1a3d"
LEAD = LH + 34
HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
SPDX-FileCopyrightText: 2026 jerbanpls
SPDX-License-Identifier: GPL-3.0-or-later
Generated by packaging/branding/make_logo.py. Original artwork; no game imagery.
-->
"""
DEFS = """<defs>
<linearGradient id="g0" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="70"><stop offset="0" stop-color="#ffe08a"/><stop offset=".55" stop-color="#ffb35c"/><stop offset="1" stop-color="#f0645a"/></linearGradient>
<linearGradient id="g1" gradientUnits="userSpaceOnUse" x1="0" y1="104" x2="0" y2="174"><stop offset="0" stop-color="#ffe08a"/><stop offset=".55" stop-color="#ffb35c"/><stop offset="1" stop-color="#f0645a"/></linearGradient>
<linearGradient id="ringg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#ffd36b"/><stop offset="1" stop-color="#f0645a"/></linearGradient>
<linearGradient id="sky" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#ff9a5a"/><stop offset="1" stop-color="#ffd9a0"/></linearGradient>
<clipPath id="disc"><circle cx="256" cy="256" r="162"/></clipPath>
<clipPath id="oclip"><circle cx="25" cy="35" r="19"/></clipPath>
<symbol id="mark" viewBox="0 0 512 512">
<circle cx="256" cy="256" r="186" fill="none" stroke="url(#ringg)" stroke-width="30" stroke-dasharray="1040 129" transform="rotate(-80 256 256)"/>
<rect x="368" y="62" width="44" height="44" fill="#fff3d0" transform="rotate(45 390 84)"/>
<g clip-path="url(#disc)" shape-rendering="crispEdges">
<rect x="90" y="90" width="332" height="332" fill="url(#sky)"/><rect x="300" y="150" width="56" height="56" fill="#fff6dc"/>
<path d="M90 246h56v-28h56v-28h56v28h56v28h56v28h56v156H90z" fill="#b05a8c"/>
<path d="M90 288h112v-28h28v28h56v28h56v-28h56v28H430v140H90z" fill="#4b3f86"/>
<path d="M90 354h84v28h84v-28h56v-28h56v28h56v100H90z" fill="#1d1a3d"/>
</g></symbol>
</defs>
"""

def rects(ch, x, y):
    out = []
    for r, row in enumerate(G[ch].split(",")):
        c = 0
        while c < 5:
            if row[c] == "1":
                s = c
                while c < 5 and row[c] == "1":
                    c += 1
                out.append(f'<rect x="{x + s * CELL}" y="{y + r * CELL}" width="{(c - s) * CELL}" height="{CELL}"/>')
            else:
                c += 1
    return "".join(out)

def ring_o(x, y, outline):
    cx, cy = x + 25, y + 35
    rot = f'transform="rotate(-70 {cx} {cy})"'
    dia = f'<rect x="{cx + 12}" y="{cy - 34}" width="14" height="14" transform="rotate(45 {cx + 19} {cy - 27})"'
    if outline:
        return (f'<circle cx="{cx}" cy="{cy}" r="26" fill="none" stroke="{DARK}" stroke-width="17" stroke-dasharray="140 23.4" {rot}/>'
                f'{dia} fill="{DARK}" stroke="{DARK}" stroke-width="6"/>')
    return (f'<circle cx="{cx}" cy="{cy}" r="26" fill="none" stroke="url(#ringg)" stroke-width="9" stroke-dasharray="140 23.4" {rot}/>'
            f'{dia} fill="#fff3d0"/><g transform="translate({x} {y})"><g clip-path="url(#oclip)" shape-rendering="crispEdges">'
            '<rect x="0" y="10" width="50" height="50" fill="url(#sky)"/><rect x="31" y="20" width="8" height="8" fill="#fff6dc"/>'
            '<path d="M0 40h14v-6h12v6h12v6h12v20H0z" fill="#b05a8c"/><path d="M0 50h22v-4h10v8h18v14H0z" fill="#4b3f86"/>'
            '<path d="M0 58h16v4h14v-4h20v10H0z" fill="#1d1a3d"/></g></g>')

def line(text, x0, y0, ring):
    shadow = outline = fill = ""
    x = x0
    for i, ch in enumerate(text):
        if ring and i == 3:
            outline += ring_o(x, y0, True)
            fill_ring = ring_o(x, y0, False)
        else:
            r = rects(ch, x, y0)
            shadow += r; outline += r; fill += r
        x += LW + GAP
    return shadow, outline, fill, (fill_ring if ring else "")

def wordmark():
    w1, w2 = 9 * LW + 8 * GAP, 6 * LW + 5 * GAP
    s1, o1, f1, _ = line("TRIGGERED", 0, 0, False)
    s2, o2, f2, ring = line("CHRONO", (w1 - w2) // 2, LEAD, True)
    svg = (f'<g fill="{DARK}" stroke="{DARK}" stroke-width="8" transform="translate(5 6)" opacity=".55" shape-rendering="crispEdges">{s1}{s2}</g>'
           f'<g fill="{DARK}" stroke="{DARK}" stroke-width="8" shape-rendering="crispEdges">{o1}{o2}</g>'
           f'<g fill="url(#g0)" shape-rendering="crispEdges">{f1}</g>'
           f'<g fill="url(#g1)" shape-rendering="crispEdges">{f2}</g>{ring}')
    return svg, w1, LEAD + LH

def build(kind):
    wm, w, h = wordmark()
    pad = 30
    if kind == "wordmark":
        W, H = w + 2 * pad, h + 2 * pad
        body = f'<g transform="translate({pad} {pad})">{wm}</g>'
    elif kind == "stacked":
        m = 250
        W, H = w + 2 * pad, m + 20 + h + 2 * pad
        body = (f'<use href="#mark" x="{(W - m) // 2}" y="{pad}" width="{m}" height="{m}"/>'
                f'<g transform="translate({pad} {pad + m + 20})">{wm}</g>')
    else:
        m = 190
        W, H = 2 * pad + m + 30 + w, max(m, h) + 2 * pad
        body = (f'<use href="#mark" x="{pad}" y="{(H - m) // 2}" width="{m}" height="{m}"/>'
                f'<g transform="translate({pad + m + 30} {(H - h) // 2})">{wm}</g>')
    return W, H, (f'{HEADER}<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W * 2}" height="{H * 2}" role="img" aria-label="Triggered Chrono">\n{DEFS}{body}\n</svg>\n')

def png(svg, out, width):
    if shutil.which("rsvg-convert"):
        subprocess.run(["rsvg-convert", "-w", str(width), "-o", out, svg], check=True)
    else:
        exe = shutil.which("magick") or shutil.which("convert")
        subprocess.run([exe, "-background", "none", "-density", "300", svg, "-resize", f"{width}x", out], check=True)

if __name__ == "__main__":
    for kind in ("stacked", "horizontal", "wordmark"):
        W, H, s = build(kind)
        p = os.path.join(HERE, f"triggered-chrono-{kind}.svg")
        open(p, "w").write(s)
        png(p, p[:-4] + ".png", 1200 if kind != "horizontal" else 1600)
        print("wrote", os.path.basename(p))
