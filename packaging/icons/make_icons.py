"""Generate the CT Recomp app icon and the Steam library artwork.

Everything is drawn from the code below: an abstract time-ring around a small
pixel diorama (a square sun over stepped hills). No game art, no fonts (the
wordmark is a 5x7 pixel face drawn here), nothing traced or copied.

  packaging/icons/make_icons.py            write ct-recomp.svg + PNGs (16..512)
  packaging/icons/make_icons.py --steam    also write packaging/steam/artwork/

PNGs are rasterised with rsvg-convert, else ImageMagick (magick/convert).
The outputs are committed, so building a package needs none of this.
"""
import os
import random
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SIZES = (16, 24, 32, 48, 64, 128, 256, 512)

DEFS = """<defs>
  <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#3a2f6b"/><stop offset="1" stop-color="#1d1a3d"/>
  </linearGradient>
  <linearGradient id="ring" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#ffd36b"/><stop offset="1" stop-color="#f0645a"/>
  </linearGradient>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#ff9a5a"/><stop offset="1" stop-color="#ffd9a0"/>
  </linearGradient>
  <clipPath id="disc"><circle cx="256" cy="256" r="162"/></clipPath>
</defs>"""


def emblem():
    """The mark on a 512 canvas: time-ring (open at the upper right) + diorama."""
    s = ['<circle cx="256" cy="256" r="186" fill="none" stroke="url(#ring)" '
         'stroke-width="30" stroke-dasharray="1040 129" '
         'transform="rotate(-80 256 256)"/>',
         # the gem at the gap's end, a "now" marker
         '<rect x="368" y="62" width="44" height="44" fill="#fff3d0" '
         'transform="rotate(45 390 84)"/>',
         '<g clip-path="url(#disc)" shape-rendering="crispEdges">',
         '<rect x="90" y="90" width="332" height="332" fill="url(#sky)"/>',
         '<rect x="300" y="150" width="56" height="56" fill="#fff6dc"/>']
    u = 28   # pixel unit

    def steps(color, base, heights, x0=94):
        return [f'<rect x="{x0 + i * u}" y="{base - h * u}" width="{u}" '
                f'height="{h * u + 400}" fill="{color}"/>'
                for i, h in enumerate(heights)]
    s += steps('#b05a8c', 330, [3, 3, 4, 4, 5, 5, 4, 3, 3, 2, 2, 3])
    s += steps('#4b3f86', 372, [3, 3, 2, 2, 3, 4, 4, 3, 2, 2, 3, 3])
    s += steps('#1d1a3d', 410, [2, 2, 2, 1, 1, 1, 2, 2, 3, 3, 2, 2])
    # a pixel tree on the near hill
    s += ['<rect x="150" y="296" width="14" height="30" fill="#1d1a3d"/>',
          '<rect x="136" y="268" width="42" height="14" fill="#1d1a3d"/>',
          '<rect x="122" y="282" width="70" height="14" fill="#1d1a3d"/>',
          '<rect x="136" y="254" width="28" height="14" fill="#1d1a3d"/>']
    s.append('</g>')
    return "\n".join(s)


def icon_svg():
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!--
SPDX-FileCopyrightText: 2026 jerbanpls
SPDX-License-Identifier: GPL-3.0-or-later
Generated by packaging/icons/make_icons.py. An abstract time-ring around a
pixel diorama. Original artwork; no game imagery.
-->
<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
{DEFS}
<rect x="8" y="8" width="496" height="496" rx="108" fill="url(#tile)"/>
{emblem()}
</svg>
"""


FONT = {  # 5x7 pixel face, only the letters the wordmark needs
    'C': "01110 10001 10000 10000 10000 10001 01110",
    'T': "11111 00100 00100 00100 00100 00100 00100",
    'R': "11110 10001 10001 11110 10100 10010 10001",
    'E': "11111 10000 10000 11110 10000 10000 11111",
    'O': "01110 10001 10001 10001 10001 10001 01110",
    'M': "10001 11011 10101 10101 10001 10001 10001",
    'P': "11110 10001 10001 11110 10000 10000 10000",
}


def text_width(text, px):
    return sum(3 * px if c == ' ' else 6 * px for c in text) - px


def word(text, x, y, px, fill, shadow="#1d1a3d"):
    """Pixel text, left edge x, top y, px per cell."""
    back, front, cx = [], [], x
    for ch in text:
        if ch == ' ':
            cx += 3 * px
            continue
        for r, row in enumerate(FONT[ch].split()):
            for c, bit in enumerate(row):
                if bit == '1':
                    X, Y = cx + c * px, y + r * px
                    back.append(f'<rect x="{X + px // 3}" y="{Y + px // 3}" '
                                f'width="{px}" height="{px}" fill="{shadow}"/>')
                    front.append(f'<rect x="{X}" y="{Y}" width="{px}" '
                                 f'height="{px}" fill="{fill}"/>')
        cx += 6 * px
    return '<g shape-rendering="crispEdges">' + "".join(back + front) + '</g>'


def place(x, y, size):   # the emblem scaled into a size x size box at x,y
    return (f'<g transform="translate({x} {y}) scale({size / 512})">'
            f'{emblem()}</g>')


def backdrop(w, h, seed):
    rnd = random.Random(seed)
    s = [f'<rect width="{w}" height="{h}" fill="url(#bg)"/>']
    for _ in range(max(20, w * h // 9000)):
        x, y = rnd.randrange(w) // 6 * 6, rnd.randrange(int(h * .6)) // 6 * 6
        s.append(f'<rect x="{x}" y="{y}" width="6" height="6" fill="#fff3d0" '
                 f'opacity="{rnd.choice((.25, .4, .7))}" shape-rendering="crispEdges"/>')
    u = max(12, h // 36)
    for col, base, amp in (('#7a4a8f', .80, 3), ('#3f3678', .88, 3),
                           ('#1d1a3d', .95, 2)):
        x, hgt = 0, rnd.randrange(2, 5)
        while x < w:
            hgt = max(1, min(amp + 2, hgt + rnd.choice((-1, 0, 0, 1))))
            top = int(h * base) // u * u - hgt * u
            s.append(f'<rect x="{x}" y="{top}" width="{u}" height="{h - top}" '
                     f'fill="{col}" shape-rendering="crispEdges"/>')
            x += u
    return "\n".join(s)


def wrap(w, h, body):
    bg = ('<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">'
          '<stop offset="0" stop-color="#241f4f"/><stop offset=".7" stop-color="#6a3f80"/>'
          '<stop offset="1" stop-color="#d9735f"/></linearGradient>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="0 0 {w} {h}">{DEFS}{bg}\n{body}\n</svg>')


def steam_svgs():
    """name -> (width, height, svg). The name text is added by packaging/branding/make_logo.py."""
    cream = "#fff3d0"
    tw = text_width("CT RECOMP", 10)
    out = {}
    out["grid.png"] = (600, 900, wrap(600, 900, backdrop(600, 900, 1)
                       + place(100, 150, 400)))
    out["capsule_wide.png"] = (920, 430, wrap(920, 430, backdrop(920, 430, 2)
                               + place(40, 15, 400)))
    out["hero.png"] = (1920, 620, wrap(1920, 620, backdrop(1920, 620, 3)
                       + place(1380, 90, 440)))
    px = 18
    out["logo.png"] = (1280, 720, wrap(1280, 720, place(440, 20, 400)))
    out["icon.png"] = (256, 256, icon_svg())
    return out


def rasteriser():
    if shutil.which("rsvg-convert"):
        return lambda svg, png, w, h: subprocess.run(
            ["rsvg-convert", "-w", str(w), "-h", str(h), "-o", png, svg], check=True)
    im = shutil.which("magick") or shutil.which("convert")
    if im:
        return lambda svg, png, w, h: subprocess.run(
            [im, "-background", "none", "-density", "384", svg,
             "-resize", f"{w}x{h}!", "-strip", png], check=True)
    sys.exit("need rsvg-convert or ImageMagick to rasterise")


def write(path, text):
    with open(path, "w") as f:
        f.write(text)


def main():
    raster = rasteriser()
    svg_path = os.path.join(HERE, "ct-recomp.svg")
    write(svg_path, icon_svg())
    for n in SIZES:
        d = os.path.join(HERE, f"{n}x{n}")
        os.makedirs(d, exist_ok=True)
        raster(svg_path, os.path.join(d, "ct-recomp.png"), n, n)
    if "--steam" in sys.argv:
        art = os.path.join(ROOT, "packaging", "steam", "artwork")
        os.makedirs(art, exist_ok=True)
        with tempfile.TemporaryDirectory(dir=art) as tmp:
            for name, (w, h, s) in steam_svgs().items():
                p = os.path.join(tmp, name + ".svg")
                write(p, s)
                raster(p, os.path.join(art, name), w, h)


if __name__ == "__main__":
    main()
